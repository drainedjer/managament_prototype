-- =============================================================================
-- CasaBatangueño: Apartment & Dormitory Rental Management System
-- PostgreSQL Schema (Neon Postgres / Vercel Marketplace Ready)
-- =============================================================================

-- 1. Users (RBAC: admin, owner, staff, customer)
CREATE TABLE IF NOT EXISTS users (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  full_name VARCHAR(120) NOT NULL,
  email VARCHAR(150) NOT NULL UNIQUE,
  password_hash VARCHAR(255) NOT NULL,
  role VARCHAR(20) NOT NULL DEFAULT 'customer'
    CHECK (role IN ('admin', 'owner', 'staff', 'customer')),
  owner_id INTEGER DEFAULT NULL,
  phone VARCHAR(30) NOT NULL DEFAULT '',
  is_active BOOLEAN NOT NULL DEFAULT TRUE,
  failed_login_attempts INTEGER NOT NULL DEFAULT 0,
  locked_until TIMESTAMPTZ DEFAULT NULL,
  consent_accepted_at TIMESTAMPTZ DEFAULT NULL,
  archived_at TIMESTAMPTZ DEFAULT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_users_role ON users (role);
CREATE INDEX IF NOT EXISTS idx_users_email_lower ON users (LOWER(email));

-- 2. Owners
CREATE TABLE IF NOT EXISTS owners (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id INTEGER NOT NULL UNIQUE REFERENCES users(id) ON DELETE CASCADE,
  business_name VARCHAR(150) NOT NULL,
  tax_id VARCHAR(60) DEFAULT NULL,
  billing_address VARCHAR(255) DEFAULT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- Add FK from users.owner_id -> owners.id if not already present
DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint WHERE conname = 'fk_users_owner_id'
  ) THEN
    ALTER TABLE users
      ADD CONSTRAINT fk_users_owner_id
      FOREIGN KEY (owner_id) REFERENCES owners(id) ON DELETE SET NULL;
  END IF;
END $$;

-- 3. Properties
CREATE TABLE IF NOT EXISTS properties (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  owner_id INTEGER NOT NULL REFERENCES owners(id) ON DELETE CASCADE,
  name VARCHAR(150) NOT NULL,
  property_type VARCHAR(40) NOT NULL
    CHECK (property_type IN ('Apartment', 'Dormitory', 'Boarding House', 'Studio Unit', 'Shared Room', 'Private Room')),
  address VARCHAR(255) NOT NULL,
  city VARCHAR(100) NOT NULL DEFAULT 'Batangas City',
  latitude NUMERIC(10, 7) NOT NULL DEFAULT 13.7845,
  longitude NUMERIC(10, 7) NOT NULL DEFAULT 121.0735,
  description TEXT NOT NULL DEFAULT '',
  monthly_price NUMERIC(12, 2) NOT NULL DEFAULT 0.00,
  house_rules TEXT NOT NULL DEFAULT '',
  is_published BOOLEAN NOT NULL DEFAULT TRUE,
  contact_phone VARCHAR(30) NOT NULL DEFAULT '',
  contact_email VARCHAR(150) NOT NULL DEFAULT '',
  location_access VARCHAR(255) DEFAULT '',
  nearby_places TEXT DEFAULT '',
  landmarks TEXT DEFAULT '',
  walking_minutes_bsu INTEGER DEFAULT NULL,
  tricycle_minutes_bsu INTEGER DEFAULT NULL,
  min_lease_months INTEGER NOT NULL DEFAULT 6,
  deposit_policy TEXT DEFAULT '',
  utilities_policy TEXT DEFAULT '',
  inclusions TEXT DEFAULT '',
  curfew_policy TEXT DEFAULT '',
  archived_at TIMESTAMPTZ DEFAULT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_properties_owner ON properties (owner_id);
CREATE INDEX IF NOT EXISTS idx_properties_published ON properties (is_published, archived_at);

-- 4. Buildings
CREATE TABLE IF NOT EXISTS buildings (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  property_id INTEGER NOT NULL REFERENCES properties(id) ON DELETE CASCADE,
  name VARCHAR(120) NOT NULL,
  floors INTEGER NOT NULL DEFAULT 1 CHECK (floors >= 1),
  description VARCHAR(255) NOT NULL DEFAULT '',
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 5. Rooms
CREATE TABLE IF NOT EXISTS rooms (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  property_id INTEGER NOT NULL REFERENCES properties(id) ON DELETE CASCADE,
  building_id INTEGER NOT NULL REFERENCES buildings(id) ON DELETE CASCADE,
  floor_number INTEGER NOT NULL DEFAULT 1,
  room_number VARCHAR(30) NOT NULL,
  room_type VARCHAR(40) NOT NULL
    CHECK (room_type IN ('Apartment', 'Dormitory', 'Boarding House', 'Studio Unit', 'Shared Room', 'Private Room')),
  capacity INTEGER NOT NULL DEFAULT 1 CHECK (capacity >= 1),
  occupied_beds INTEGER NOT NULL DEFAULT 0 CHECK (occupied_beds >= 0),
  monthly_price NUMERIC(12, 2) NOT NULL CHECK (monthly_price >= 0),
  status VARCHAR(20) NOT NULL DEFAULT 'Available'
    CHECK (status IN ('Available', 'Occupied', 'Reserved', 'Maintenance')),
  description TEXT NOT NULL DEFAULT '',
  last_vacated_at DATE DEFAULT NULL,
  archived_at TIMESTAMPTZ DEFAULT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT uq_building_room UNIQUE (building_id, room_number)
);

CREATE INDEX IF NOT EXISTS idx_rooms_property ON rooms (property_id);
CREATE INDEX IF NOT EXISTS idx_rooms_status ON rooms (status, archived_at);

-- 6. Amenities & Property Amenities
CREATE TABLE IF NOT EXISTS amenities (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(80) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS property_amenities (
  property_id INTEGER NOT NULL REFERENCES properties(id) ON DELETE CASCADE,
  amenity_id INTEGER NOT NULL REFERENCES amenities(id) ON DELETE CASCADE,
  PRIMARY KEY (property_id, amenity_id)
);

-- 7. Property Images & Room Images
CREATE TABLE IF NOT EXISTS property_images (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  property_id INTEGER NOT NULL REFERENCES properties(id) ON DELETE CASCADE,
  image_url VARCHAR(500) NOT NULL,
  is_primary BOOLEAN NOT NULL DEFAULT FALSE,
  sort_order INTEGER NOT NULL DEFAULT 0,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS room_images (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  room_id INTEGER NOT NULL REFERENCES rooms(id) ON DELETE CASCADE,
  image_url VARCHAR(500) NOT NULL,
  is_primary BOOLEAN NOT NULL DEFAULT FALSE,
  sort_order INTEGER NOT NULL DEFAULT 0,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 8. Tenants
CREATE TABLE IF NOT EXISTS tenants (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id INTEGER DEFAULT NULL REFERENCES users(id) ON DELETE SET NULL,
  owner_id INTEGER NOT NULL REFERENCES owners(id) ON DELETE CASCADE,
  full_name VARCHAR(120) NOT NULL,
  email VARCHAR(150) NOT NULL DEFAULT '',
  contact_number VARCHAR(30) NOT NULL DEFAULT '',
  address VARCHAR(255) NOT NULL DEFAULT '',
  emergency_contact VARCHAR(150) NOT NULL DEFAULT '',
  property_id INTEGER NOT NULL REFERENCES properties(id) ON DELETE RESTRICT,
  room_id INTEGER DEFAULT NULL REFERENCES rooms(id) ON DELETE SET NULL,
  move_in_date DATE NOT NULL,
  move_out_date DATE DEFAULT NULL,
  monthly_rent NUMERIC(12, 2) NOT NULL DEFAULT 0.00,
  security_deposit NUMERIC(12, 2) NOT NULL DEFAULT 0.00,
  status VARCHAR(20) NOT NULL DEFAULT 'Active'
    CHECK (status IN ('Active', 'Pending', 'Inactive', 'Former Tenant')),
  move_in_checklist JSONB DEFAULT NULL,
  move_out_checklist JSONB DEFAULT NULL,
  deposit_deductions NUMERIC(12, 2) NOT NULL DEFAULT 0.00,
  deposit_refunded NUMERIC(12, 2) NOT NULL DEFAULT 0.00,
  deposit_refunded_at DATE DEFAULT NULL,
  archived_at TIMESTAMPTZ DEFAULT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_tenants_owner_status ON tenants (owner_id, status, archived_at);

-- 9. Leases
CREATE TABLE IF NOT EXISTS leases (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id INTEGER NOT NULL REFERENCES tenants(id) ON DELETE CASCADE,
  owner_id INTEGER NOT NULL REFERENCES owners(id) ON DELETE CASCADE,
  property_id INTEGER NOT NULL REFERENCES properties(id) ON DELETE RESTRICT,
  room_id INTEGER DEFAULT NULL REFERENCES rooms(id) ON DELETE SET NULL,
  start_date DATE NOT NULL,
  end_date DATE NOT NULL,
  monthly_rate NUMERIC(12, 2) NOT NULL,
  deposit_amount NUMERIC(12, 2) NOT NULL DEFAULT 0.00,
  status VARCHAR(20) NOT NULL DEFAULT 'Active'
    CHECK (status IN ('Active', 'Expiring', 'Completed', 'Terminated')),
  renewal_notified_at TIMESTAMPTZ DEFAULT NULL,
  notes TEXT NOT NULL DEFAULT '',
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_leases_end_date ON leases (end_date, status);

-- 10. Rental Applications
CREATE TABLE IF NOT EXISTS rental_applications (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  reference_number VARCHAR(40) NOT NULL UNIQUE,
  user_id INTEGER DEFAULT NULL REFERENCES users(id) ON DELETE SET NULL,
  full_name VARCHAR(120) NOT NULL,
  email VARCHAR(150) NOT NULL,
  contact_number VARCHAR(30) NOT NULL,
  property_id INTEGER NOT NULL REFERENCES properties(id) ON DELETE CASCADE,
  preferred_room_type VARCHAR(40) NOT NULL,
  assigned_room_id INTEGER DEFAULT NULL REFERENCES rooms(id) ON DELETE SET NULL,
  expected_move_in_date DATE NOT NULL,
  reservation_date DATE DEFAULT NULL,
  occupants INTEGER NOT NULL DEFAULT 1 CHECK (occupants >= 1),
  message TEXT NOT NULL DEFAULT '',
  consent_accepted BOOLEAN NOT NULL DEFAULT FALSE,
  status VARCHAR(20) NOT NULL DEFAULT 'Pending'
    CHECK (status IN ('Pending', 'Approved', 'Rejected', 'Reserved', 'Completed', 'Cancelled')),
  archived_at TIMESTAMPTZ DEFAULT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_applications_property_status ON rental_applications (property_id, status, archived_at);
CREATE INDEX IF NOT EXISTS idx_applications_email_lower ON rental_applications (LOWER(email));

-- 11. Private Applicant ID Documents (served only to authorized owner/admin)
CREATE TABLE IF NOT EXISTS application_documents (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  application_id INTEGER NOT NULL UNIQUE REFERENCES rental_applications(id) ON DELETE CASCADE,
  file_name VARCHAR(255) NOT NULL,
  mime_type VARCHAR(80) NOT NULL,
  file_size INTEGER NOT NULL,
  content_base64 TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 12. Reservations (holds beds in dorms and single rooms)
CREATE TABLE IF NOT EXISTS reservations (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  application_id INTEGER NOT NULL UNIQUE REFERENCES rental_applications(id) ON DELETE CASCADE,
  room_id INTEGER NOT NULL REFERENCES rooms(id) ON DELETE CASCADE,
  beds_held INTEGER NOT NULL DEFAULT 1 CHECK (beds_held >= 1),
  reserved_date DATE NOT NULL,
  expires_at DATE NOT NULL,
  status VARCHAR(20) NOT NULL DEFAULT 'Active'
    CHECK (status IN ('Active', 'Converted', 'Cancelled', 'Expired')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_reservations_room_status ON reservations (room_id, status);

-- 13. Payments (monthly billing records)
CREATE TABLE IF NOT EXISTS payments (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tenant_id INTEGER NOT NULL REFERENCES tenants(id) ON DELETE RESTRICT,
  owner_id INTEGER NOT NULL REFERENCES owners(id) ON DELETE CASCADE,
  property_id INTEGER NOT NULL REFERENCES properties(id) ON DELETE RESTRICT,
  room_id INTEGER DEFAULT NULL REFERENCES rooms(id) ON DELETE SET NULL,
  billing_month CHAR(7) NOT NULL,
  due_date DATE NOT NULL,
  amount_due NUMERIC(12, 2) NOT NULL CHECK (amount_due >= 0),
  notes VARCHAR(255) NOT NULL DEFAULT '',
  reminder_sent_at TIMESTAMPTZ DEFAULT NULL,
  overdue_notified_at TIMESTAMPTZ DEFAULT NULL,
  archived_at TIMESTAMPTZ DEFAULT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_payment_tenant_month_active
  ON payments (tenant_id, billing_month)
  WHERE archived_at IS NULL;

-- 14. Payment Transactions (installments + void/edit audit)
CREATE TABLE IF NOT EXISTS payment_transactions (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  payment_id INTEGER NOT NULL REFERENCES payments(id) ON DELETE RESTRICT,
  amount NUMERIC(12, 2) NOT NULL CHECK (amount > 0),
  payment_date DATE NOT NULL,
  payment_method VARCHAR(30) NOT NULL DEFAULT 'Cash'
    CHECK (payment_method IN ('Cash', 'GCash', 'Maya', 'Bank Transfer', 'Other')),
  reference_number VARCHAR(80) NOT NULL UNIQUE,
  receipt_number VARCHAR(80) NOT NULL UNIQUE,
  notes VARCHAR(255) NOT NULL DEFAULT '',
  recorded_by INTEGER DEFAULT NULL REFERENCES users(id) ON DELETE SET NULL,
  edit_reason TEXT DEFAULT NULL,
  edited_by INTEGER DEFAULT NULL REFERENCES users(id) ON DELETE SET NULL,
  edited_at TIMESTAMPTZ DEFAULT NULL,
  voided_at TIMESTAMPTZ DEFAULT NULL,
  void_reason TEXT DEFAULT NULL,
  voided_by INTEGER DEFAULT NULL REFERENCES users(id) ON DELETE SET NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_ptx_payment ON payment_transactions (payment_id, voided_at);
CREATE INDEX IF NOT EXISTS idx_ptx_date ON payment_transactions (payment_date);

-- 15. Expense Categories & Expenses
CREATE TABLE IF NOT EXISTS expense_categories (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(80) NOT NULL UNIQUE,
  description VARCHAR(255) NOT NULL DEFAULT ''
);

CREATE TABLE IF NOT EXISTS expenses (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  owner_id INTEGER NOT NULL REFERENCES owners(id) ON DELETE CASCADE,
  property_id INTEGER NOT NULL REFERENCES properties(id) ON DELETE CASCADE,
  category_id INTEGER NOT NULL REFERENCES expense_categories(id) ON DELETE RESTRICT,
  description VARCHAR(255) NOT NULL,
  amount NUMERIC(12, 2) NOT NULL CHECK (amount > 0),
  expense_date DATE NOT NULL,
  payment_method VARCHAR(30) NOT NULL DEFAULT 'Cash'
    CHECK (payment_method IN ('Cash', 'GCash', 'Maya', 'Bank Transfer', 'Other')),
  receipt_reference VARCHAR(100) NOT NULL DEFAULT '',
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_expenses_owner_date ON expenses (owner_id, expense_date);

-- 16. Reviews & Testimonials
CREATE TABLE IF NOT EXISTS reviews (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  property_id INTEGER NOT NULL REFERENCES properties(id) ON DELETE CASCADE,
  reviewer_name VARCHAR(120) NOT NULL,
  email VARCHAR(150) NOT NULL,
  rating SMALLINT NOT NULL CHECK (rating BETWEEN 1 AND 5),
  title VARCHAR(150) NOT NULL DEFAULT '',
  comment TEXT NOT NULL,
  status VARCHAR(20) NOT NULL DEFAULT 'Pending'
    CHECK (status IN ('Pending', 'Approved', 'Rejected')),
  owner_reply TEXT DEFAULT NULL,
  replied_at TIMESTAMPTZ DEFAULT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT uq_review_property_email UNIQUE (property_id, email)
);

CREATE TABLE IF NOT EXISTS testimonials (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  property_id INTEGER DEFAULT NULL REFERENCES properties(id) ON DELETE SET NULL,
  author_name VARCHAR(120) NOT NULL,
  role_label VARCHAR(120) NOT NULL DEFAULT 'Resident',
  rating SMALLINT NOT NULL DEFAULT 5 CHECK (rating BETWEEN 1 AND 5),
  quote TEXT NOT NULL,
  status VARCHAR(20) NOT NULL DEFAULT 'Pending'
    CHECK (status IN ('Pending', 'Approved', 'Rejected')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 17. Contact Messages
CREATE TABLE IF NOT EXISTS contact_messages (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  full_name VARCHAR(120) NOT NULL,
  email VARCHAR(150) NOT NULL,
  phone VARCHAR(30) NOT NULL DEFAULT '',
  subject VARCHAR(150) NOT NULL DEFAULT '',
  message TEXT NOT NULL,
  consent_accepted BOOLEAN NOT NULL DEFAULT FALSE,
  status VARCHAR(20) NOT NULL DEFAULT 'New'
    CHECK (status IN ('New', 'Read', 'Replied')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 18. Viewing Requests
CREATE TABLE IF NOT EXISTS viewing_requests (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  property_id INTEGER NOT NULL REFERENCES properties(id) ON DELETE CASCADE,
  user_id INTEGER DEFAULT NULL REFERENCES users(id) ON DELETE SET NULL,
  full_name VARCHAR(120) NOT NULL,
  email VARCHAR(150) NOT NULL,
  phone VARCHAR(30) NOT NULL,
  preferred_date DATE NOT NULL,
  preferred_time VARCHAR(40) NOT NULL DEFAULT '10:00 AM',
  notes TEXT NOT NULL DEFAULT '',
  consent_accepted BOOLEAN NOT NULL DEFAULT FALSE,
  status VARCHAR(20) NOT NULL DEFAULT 'Pending'
    CHECK (status IN ('Pending', 'Confirmed', 'Completed', 'Cancelled')),
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 19. Waitlist
CREATE TABLE IF NOT EXISTS waitlist (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  property_id INTEGER NOT NULL REFERENCES properties(id) ON DELETE CASCADE,
  full_name VARCHAR(120) NOT NULL,
  email VARCHAR(150) NOT NULL,
  phone VARCHAR(30) NOT NULL DEFAULT '',
  preferred_room_type VARCHAR(40) NOT NULL DEFAULT 'Any',
  consent_accepted BOOLEAN NOT NULL DEFAULT FALSE,
  status VARCHAR(20) NOT NULL DEFAULT 'Waiting'
    CHECK (status IN ('Waiting', 'Notified', 'Converted', 'Cancelled')),
  notified_at TIMESTAMPTZ DEFAULT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 20. Favorites
CREATE TABLE IF NOT EXISTS favorites (
  user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  property_id INTEGER NOT NULL REFERENCES properties(id) ON DELETE CASCADE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  PRIMARY KEY (user_id, property_id)
);

-- 21. Password Resets
CREATE TABLE IF NOT EXISTS password_resets (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  token_hash VARCHAR(128) NOT NULL UNIQUE,
  expires_at TIMESTAMPTZ NOT NULL,
  used_at TIMESTAMPTZ DEFAULT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 22. Maintenance Requests
CREATE TABLE IF NOT EXISTS maintenance_requests (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  owner_id INTEGER NOT NULL REFERENCES owners(id) ON DELETE CASCADE,
  property_id INTEGER NOT NULL REFERENCES properties(id) ON DELETE CASCADE,
  room_id INTEGER DEFAULT NULL REFERENCES rooms(id) ON DELETE SET NULL,
  tenant_id INTEGER DEFAULT NULL REFERENCES tenants(id) ON DELETE SET NULL,
  user_id INTEGER DEFAULT NULL REFERENCES users(id) ON DELETE SET NULL,
  title VARCHAR(150) NOT NULL,
  description TEXT NOT NULL,
  priority VARCHAR(20) NOT NULL DEFAULT 'Medium'
    CHECK (priority IN ('Low', 'Medium', 'High')),
  status VARCHAR(20) NOT NULL DEFAULT 'Open'
    CHECK (status IN ('Open', 'In Progress', 'Done')),
  owner_notes TEXT NOT NULL DEFAULT '',
  resolved_at TIMESTAMPTZ DEFAULT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 23. Announcements
CREATE TABLE IF NOT EXISTS announcements (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  owner_id INTEGER NOT NULL REFERENCES owners(id) ON DELETE CASCADE,
  property_id INTEGER DEFAULT NULL REFERENCES properties(id) ON DELETE CASCADE,
  title VARCHAR(150) NOT NULL,
  body TEXT NOT NULL,
  is_published BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 24. Site Settings
CREATE TABLE IF NOT EXISTS site_settings (
  key VARCHAR(80) PRIMARY KEY,
  value TEXT NOT NULL DEFAULT '',
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 25. Notifications
CREATE TABLE IF NOT EXISTS notifications (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  title VARCHAR(150) NOT NULL,
  body VARCHAR(255) NOT NULL,
  link VARCHAR(150) DEFAULT NULL,
  is_read BOOLEAN NOT NULL DEFAULT FALSE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 26. Audit Logs
CREATE TABLE IF NOT EXISTS audit_logs (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id INTEGER DEFAULT NULL REFERENCES users(id) ON DELETE SET NULL,
  action VARCHAR(100) NOT NULL,
  entity_type VARCHAR(60) NOT NULL,
  entity_id INTEGER DEFAULT NULL,
  details JSONB DEFAULT NULL,
  ip_address VARCHAR(64) DEFAULT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_audit_created ON audit_logs (created_at DESC);

-- 27. Property Views (analytics)
CREATE TABLE IF NOT EXISTS property_views (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  property_id INTEGER NOT NULL REFERENCES properties(id) ON DELETE CASCADE,
  viewed_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
